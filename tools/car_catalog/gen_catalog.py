#!/usr/bin/env python3
"""Builds src/ApexHUD.Native.Common/CarCatalog.Data.cs and tools/car_catalog/cars.json from the per-car research
files (sc_cars/out/*.json, 2026-10-28: iRacing car pages + Lovely Car Data @ 08db79e + the Garage 61 CarID list).

Rules (Angelo: "never show made-up numbers"):
  * CarPath only when verified (Lovely carId = iRacing CarPath); unverified paths are left out - those cars are
    still found by their CarID (Garage 61 list, all 91 known).
  * Shift-light rpm per gear only from Lovely Car Data.
  * Gear count only when the iRacing page states "N-speed", or Lovely lists fewer than 8 gears (Lovely pads to 8,
    so a shorter list is the car's own). Both present and different -> left out.
  * ABS / TC / hybrid only when the research marks them yes / no from a source; everything else stays unknown.
  * Story text = the research's "heritage" line, which is from the car's iRacing page.
Usage: python3 gen_catalog.py <dir with the per-car json files>
"""
import json, glob, os, re, sys

src = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.normpath(os.path.join(here, "..", ".."))

# research class -> Grandstand's class label (short, fits the tower / plates)
CLASS = {
    "GTP": "GTP", "LMP2": "LMP2", "LMP3": "LMP3", "LMP1": "LMP1", "GT3": "GT3", "GTE": "GTE", "GT4": "GT4", "GT1": "GT1",
    "TCR": "TCR", "DP": "DP", "SRF": "SRF", "Prototype (Radical)": "RADICAL", "IMSA GTP (1980s)": "CLASSIC", "GTO": "CLASSIC",
    "Cup (Porsche)": "CUP", "Cup (Ferrari Challenge)": "CUP", "Cup (Clio)": "CUP", "Jetta TDI Cup": "CUP",
    "Electric GT": "EV", "GR86 Cup": "GR86", "MX-5 Cup": "MX-5", "MX-5 (2010)": "MX-5", "M2": "M2",
    "Caterham": "CATERHAM", "Solstice": "SOLSTICE", "Mustang Challenge": "MUSTANG", "Touring": "TOURING",
    "Touring (CTS-V)": "TOURING", "Ruf": "RUF", "Supercars": "SUPERCAR", "Supercars (Gen2)": "SUPERCAR",
    "V8 Supercars (legacy)": "SUPERCAR", "Stock Car Brasil": "SCB", "NASCAR Euro": "NASCAR",
}

def yesno(v):
    if not v or not isinstance(v, str): return None
    v = v.strip().lower()
    if v.startswith("yes"): return True
    if v.startswith("no") and "not stated" not in v: return False
    return None

def cs(s):
    return "null" if s is None else '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def cb(b):
    return "null" if b is None else ("true" if b else "false")

rows, out, counts = [], [], {}
for f in sorted(glob.glob(os.path.join(src, "*.json"))):
    if os.path.basename(f).startswith("_"): continue
    c = json.load(open(f))
    name = c["display_name"]
    cls = c["class"]
    if cls == "GT2 / GT3 (legacy)": label = "GT2" if name.endswith("GT2") else "GT3"
    else: label = CLASS[cls]
    path = c["car_path"] if (c.get("car_path_status") or "").startswith("verified") else None
    slug = c["logo"]["grandstand_slug"]
    if "Corvette" in name: slug = "Corvette"          # Angelo 2026-10-18: every Corvette shows the crossflags
    maker = c["manufacturer"] or ("Ruf" if name.startswith("Ruf") else None)
    hybrid = c.get("hybrid")
    electric = isinstance(hybrid, str) and "electric" in hybrid.lower() and not hybrid.lower().startswith("yes")
    hy = None if electric else yesno(hybrid)
    abs_ = yesno(c["aids"].get("abs")); tc = yesno(c["aids"].get("tc"))
    sl = c.get("shift_lights") or {}
    rl = sl.get("redline_rpm_by_gear") or {}
    shift = [int(rl[k]) for k in sorted(rl, key=int)]
    g_page = None
    m = re.search(r"(\d)-speed", c.get("gearbox") or "")
    if m: g_page = int(m.group(1))
    g_lovely = len(shift) if 0 < len(shift) < 8 else None
    if g_page and g_lovely and g_page != g_lovely: gears = 0
    else: gears = g_page or g_lovely or 0
    if gears and len(shift) > gears: shift = shift[:gears]
    story = c.get("heritage")
    rows.append(f'        new({c["iracing_car_id"]}, {cs(path)}, {cs(name)}, "{label}", {cs(slug)}, {cs(maker)}, '
                f'{cb(hy)}, {cb(electric)}, {cb(abs_)}, {cb(tc)}, {gears}, '
                f'[{", ".join(map(str, shift))}], {cs(story)}),')
    out.append(dict(car_id=c["iracing_car_id"], car_path=path, name=name, class_label=label, research_class=cls, logo=slug,
                    maker=maker, hybrid=hy, electric=electric, abs=abs_, tc=tc, gears=gears, shift_rpm_by_gear=shift,
                    story=story, sources=c["sources"], unverified=c["unverified"]))
    for k, v in (("path", path), ("logo", slug), ("hybrid_known", hy), ("abs_known", abs_), ("tc_known", tc),
                 ("gears", gears or None), ("shift", shift or None), ("story", story)):
        if v is not None: counts[k] = counts.get(k, 0) + 1

hdr = """// <auto-generated> by tools/car_catalog/gen_catalog.py from the 2026-10-28 per-car research (tools/car_catalog/cars.json:
// iRacing's car pages, Lovely Car Data @ 08db79e, the Garage 61 CarID list). Re-run the script instead of editing.
// Only sourced values are here; null / 0 / [] = not verified, and Grandstand then shows nothing for it.
namespace ApexHUD.Native.Common;

public static partial class CarCatalog
{
    // CarId, verified CarPath, name, class label, maker logo slug, maker (text), hybrid, electric, ABS, TC, gears,
    // shift-light rpm per gear (Lovely ledRpm[0]), story line (iRacing's car page)
    static readonly CarInfo[] All =
    [
"""
open(os.path.join(repo, "src", "ApexHUD.Native.Common", "CarCatalog.Data.cs"), "w").write(hdr + "\n".join(rows) + "\n    ];\n}\n")
json.dump(out, open(os.path.join(here, "cars.json"), "w"), indent=1, ensure_ascii=False)
print(len(rows), "cars;", counts)
